const FALLBACK_PICTURES = ['📘', '🐝', '🌟', '🔤', '📝'];

function hashWord(word: string): number {
  let h = 0;
  for (let i = 0; i < word.length; i += 1) h = (h + word.charCodeAt(i) * (i + 1)) % 997;
  return h;
}

/** Look up a picture + meaning cue for a spelling word. */
export function getWordCue(word: string): WordCue {
  const key = word.trim().toLowerCase();
  const known = WORD_CUES[key];
  if (known) return known;

  return {
    picture: FALLBACK_PICTURES[hashWord(key) % FALLBACK_PICTURES.length],
    meaning: 'Think about what this word means, then spell it.',
  };
}
